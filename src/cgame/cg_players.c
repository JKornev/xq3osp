// OSP: colours from "c1" / "c2"
// (CG_OSPColorsFromString / CG_OSPColorFromChar), round team "rt", coached team "st", no "tt" / "tl";
// models: the own model for the local client (and, when it changes, every other client is
// reloaded), cg_enemyModel / cg_enemyColors for enemies, red / blue skins of the round team

				if ( slash && Q_stricmp( slash, "pm" ) ) {
					slash = NULL;
				}
				if ( cgs.clientinfo[cg.clientNum].rt != TEAM_SPECTATOR && !slash &&
					( newInfo.rt == TEAM_RED || newInfo.rt == TEAM_BLUE ) ) {
					slash = skins[( newInfo.rt - TEAM_RED ) ^ swap];
				}
				if ( !slash || cgs.clientinfo[cg.clientNum].rt == TEAM_SPECTATOR ) {
					slash = ( newInfo.rt == TEAM_BLUE ) ? "blue" : "red";
				}
